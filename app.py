
import streamlit as st
import pandas as pd
import joblib

# Load the trained model
model = joblib.load("student_performance_model.pkl")

st.title("Student Performance Prediction")
st.write("Enter student details to estimate their exam score.")

# Numerical inputs
hours = st.number_input("Hours Studied", 0, 50, 25)
attendance = st.number_input("Attendance (%)", 0, 100, 90)
sleep = st.number_input("Sleep Hours", 0, 24, 8)
previous = st.number_input("Previous Scores", 0, 100, 85)
tutoring = st.number_input("Tutoring Sessions", 0, 20, 2)
activity = st.number_input("Physical Activity (hours)", 0, 24, 3)

# Categorical inputs
parental = st.selectbox("Parental Involvement", ["Low", "Medium", "High"])
resources = st.selectbox("Access to Resources", ["Low", "Medium", "High"])
extra = st.selectbox("Extracurricular Activities", ["Yes", "No"])
motivation = st.selectbox("Motivation Level", ["Low", "Medium", "High"])
internet = st.selectbox("Internet Access", ["Yes", "No"])
income = st.selectbox("Family Income", ["Low", "Medium", "High"])
teacher = st.selectbox("Teacher Quality", ["Low", "Medium", "High"])
school = st.selectbox("School Type", ["Public", "Private"])
peer = st.selectbox("Peer Influence", ["Positive", "Neutral", "Negative"])
disability = st.selectbox("Learning Disabilities", ["Yes", "No"])
education = st.selectbox(
    "Parental Education Level",
    ["High School", "College", "Postgraduate"]
)
distance = st.selectbox(
    "Distance from Home",
    ["Near", "Moderate", "Far"]
)
gender = st.selectbox("Gender", ["Male", "Female"])

# Predict button
if st.button("Predict Exam Score"):

    student = pd.DataFrame([{
        "Hours_Studied": hours,
        "Attendance": attendance,
        "Parental_Involvement": parental,
        "Access_to_Resources": resources,
        "Extracurricular_Activities": extra,
        "Sleep_Hours": sleep,
        "Previous_Scores": previous,
        "Motivation_Level": motivation,
        "Internet_Access": internet,
        "Tutoring_Sessions": tutoring,
        "Family_Income": income,
        "Teacher_Quality": teacher,
        "School_Type": school,
        "Peer_Influence": peer,
        "Physical_Activity": activity,
        "Learning_Disabilities": disability,
        "Parental_Education_Level": education,
        "Distance_from_Home": distance,
        "Gender": gender
    }])

    prediction = model.predict(student)[0]

    st.success(f"Predicted Exam Score: {prediction:.2f}")
    st.caption("This is an estimate generated by a machine learning model.")
